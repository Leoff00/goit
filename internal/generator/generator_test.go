func TestGeneratePreservesBody(t *testing.T) {
	for _, newline := range []string{"\n", "\r\n"} {
		t.Run(strings.ReplaceAll(newline, "\r", "CR"), func(t *testing.T) {
			body := []byte("import \"testing\"" + newline + newline + "func helper() int { return 42 }" + newline + "func TestValue(t *testing.T) { if helper() != 42 { t.Fatal(\"bad\") } }")
			original := append([]byte(nil), body...)
			got, err := Generate(&inlineparser.Result{PackageName: "sample", Block: &inlineparser.Block{TestSource: body}})
			if err != nil {
				t.Fatal(err)
			}
			want := append([]byte("package sample\n\n"), body...)
			want = append(want, '\n')
			if !bytes.Equal(got, want) {
				t.Fatalf("generated bytes differ\n got: %q\nwant: %q", got, want)
			}
			if !bytes.Equal(body, original) {
				t.Fatal("generator mutated input body")
			}
			if _, err := parser.ParseFile(token.NewFileSet(), "generated_test.go", got, parser.AllErrors); err != nil {
				t.Fatalf("generated source does not parse: %v", err)
			}
		})
	}
}

func TestGenerateAddsNoExtraNewlineWhenPresent(t *testing.T) {
	body := []byte("func TestX() {}\n")
	got, err := Generate(&inlineparser.Result{PackageName: "sample", Block: &inlineparser.Block{TestSource: body}})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got[len("package sample\n\n"):], body) {
		t.Fatalf("body changed: %q", got)
	}
}

func TestGenerateRejectsInvalidStructure(t *testing.T) {
	cases := []struct {
		name   string
		result *inlineparser.Result
	}{
		{"nil result", nil},
		{"nil block", &inlineparser.Result{PackageName: "sample"}},
		{"empty package", &inlineparser.Result{Block: &inlineparser.Block{}}},
		{"keyword package", &inlineparser.Result{PackageName: "func", Block: &inlineparser.Block{}}},
		{"invalid package", &inlineparser.Result{PackageName: "bad-name", Block: &inlineparser.Block{}}},
		{"invalid body", &inlineparser.Result{PackageName: "sample", Block: &inlineparser.Block{TestSource: []byte("func Test( {")}}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Generate(tc.result)
			if err == nil || got != nil {
				t.Fatalf("Generate() = (%q, %v), want (nil, error)", got, err)
			}
		})
	}
}

func TestIntegrationGenerateAndRun(t *testing.T) {
	if testing.Short() {
		t.Skip("integration test invokes the Go toolchain")
	}
	temp := t.TempDir()
	source := "package fixture\n/*goit:test\nimport \"testing\"\nfunc helper() int { return 7 }\nfunc TestInline(t *testing.T) { if helper() != 7 { t.Fatal(\"unexpected\") } }\ngo" + "it:end*/\n"
	parsed, err := inlineparser.Parse("fixture.go", []byte(source))
	if err != nil {
		t.Fatal(err)
	}
	generated, err := Generate(parsed)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(temp, "go.mod"), []byte("module fixture\n\ngo 1.26.0\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(temp, "fixture_test.go"), generated, 0o600); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 45*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", "test", "-count=1", ".")
	cmd.Dir = temp
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOPROXY=off")
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go test failed: %v\n%s", err, output)
	}
}
